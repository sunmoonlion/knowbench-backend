"""Generate the authoring consumer's model and schema from the runtime provider."""

import argparse
import hashlib
import json
import sys
from pathlib import Path

base = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(base))
from app.domain.workbench.method_capabilities import (  # noqa: E402
    AuthorCapabilityCatalog,
    MethodCapabilities,
)

parser = argparse.ArgumentParser()
parser.add_argument("--consumer", type=Path, required=True)
args = parser.parse_args()
source = (
    (base / "app/domain/workbench/method_capabilities.py")
    .read_text()
    .split("\ndef matches_tool")[0]
)
target = args.consumer / "app/domain/knowbots/managed_capabilities_generated.py"
target.write_text(
    "# Generated by knowbench-backend/scripts/export_method_capabilities.py; do not edit.\n"
    + source
)
schema = (
    json.dumps(
        {
            "requirements": MethodCapabilities.model_json_schema(),
            "author_catalog": AuthorCapabilityCatalog.model_json_schema(),
        },
        indent=2,
    )
    + "\n"
)
(base / "contracts/method-capabilities-v1.json").write_text(schema)
lock = {
    "provider": "knowbench-backend",
    "contract": "method-capabilities-v1",
    "model_sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
    "schema_sha256": hashlib.sha256(schema.encode()).hexdigest(),
}
(args.consumer / "app/domain/knowbots/managed-capabilities-v1.lock.json").write_text(
    json.dumps(lock, indent=2) + "\n"
)
